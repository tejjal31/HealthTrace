import { jsPDF } from "jspdf";

export type PdfSection = { heading: string; lines: string[] };

/** Builds a clean, doctor-ready PDF. Hindi glyphs aren't supported by the built-in fonts, so only English text is included. */
export function downloadPdf(title: string, subtitle: string, sections: PdfSection[], filename: string) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();
  let y = 56;
  const ensure = (h: number) => {
    if (y + h > H - 50) {
      doc.addPage();
      y = 56;
    }
  };
  doc.setFont("helvetica", "bold").setFontSize(20).text(title, 48, y);
  y += 20;
  doc.setFont("helvetica", "normal").setFontSize(10).setTextColor(100).text(subtitle, 48, y);
  y += 28;
  doc.setTextColor(20);
  for (const s of sections) {
    ensure(40);
    doc.setFont("helvetica", "bold").setFontSize(13).text(s.heading, 48, y);
    y += 18;
    doc.setFont("helvetica", "normal").setFontSize(10);
    for (const line of s.lines) {
      const wrapped = doc.splitTextToSize(line, W - 96) as string[];
      ensure(wrapped.length * 14);
      doc.text(wrapped, 48, y);
      y += wrapped.length * 14 + 2;
    }
    y += 12;
  }
  ensure(30);
  doc.setFontSize(8).setTextColor(120).text(
    "Generated by HealthTrace. Values are as extracted from uploaded reports. This is not a diagnosis; please verify with the original reports.",
    48, H - 30, { maxWidth: W - 96 },
  );
  doc.save(filename);
}
